// =============================================================================
// Can you read the instrument?
// -----------------------------------------------------------------------------
// Every lesson instrument draws its numbers onto a canvas, and a canvas has no
// cascade, no rem and no user font size: every label in it is a magic number
// in a draw function. Those numbers had drifted down to eight and nine pixels
// - about four pixels of x-height - on exactly the labels a reader has to take
// a measurement off. Nobody notices, because the person writing the widget is
// looking at it from eighteen inches away on a retina display.
//
// This is the check that keeps them up. It patches the 2D context so that every
// piece of text a panel draws is recorded with its font, its box and where it
// landed, repaints the panel, and then asks three questions of the result:
//
//   1. is anything smaller than the shared minimum in js/widgetCanvas.js
//   2. is anything drawn outside the canvas, where it is simply gone
//   3. is any label sitting on top of another one
//
// The third is the one that raising type breaks, and it is why the two go
// together: bigger labels on the same axis collide, and the answer is fewer
// labels rather than smaller ones.
//
// One panel per registered widget, from the step in the catalogue that opens
// it. The list is generated by `npm run audit:scene -- --json`, and a widget
// that no lesson opens is not tested here because a reader cannot reach it.
//
// What it does not check
// -----------------------------------------------------------------------------
// Contrast, which lives in e2e/accessibility.spec.js, and whether the label
// says anything useful, which no test can decide.
// =============================================================================

