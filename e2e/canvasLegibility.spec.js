/**
 * Record every piece of text the panels draw.
 *
 * Installed before the page's own scripts, so nothing is missed on the first
 * paint. `strokeText` is patched too: an outlined label is still a label.
 */
const RECORDER = () => {
  window.__labels = [];
  const proto = CanvasRenderingContext2D.prototype;
  // An animated panel repaints sixty times a second, and without this the
  // buffer holds sixty copies of every label - which then all "overlap" each
  // other. Every widget clears its canvas at the top of a frame, so a
  // clearRect that covers the whole surface is the frame boundary.
  const clear = proto.clearRect;
  proto.clearRect = function (x, y, w, h, ...rest) {
    if (
      this.canvas?.id === 'investigationToolCanvas' &&
      x <= 0 &&
      y <= 0 &&
      w >= this.canvas.clientWidth - 1
    ) {
      window.__labels = [];
    }
    return clear.call(this, x, y, w, h, ...rest);
  };
  for (const name of ['fillText', 'strokeText']) {
    const original = proto[name];
    proto[name] = function (text, x, y, ...rest) {
      try {
        const size = parseFloat(
          String(this.font).match(/(\d+(?:\.\d+)?)px/)?.[1] || '0'
        );
        const w = this.measureText(String(text)).width;
        const h = size * 1.05;
        // In the drawing context's own coordinates first, then through the
        // current transform. Half these panels write their y-axis title
        // rotated a quarter turn, and reading the untransformed x said the
        // label was a hundred pixels off the left edge when it is sitting
        // neatly in the margin.
        const x0 =
          this.textAlign === 'center'
            ? x - w / 2
            : this.textAlign === 'right' || this.textAlign === 'end'
              ? x - w
              : x;
        const y0 =
          this.textBaseline === 'top'
            ? y
            : this.textBaseline === 'middle'
              ? y - h / 2
              : y - h * 0.8;
        const m = this.getTransform();
        const at = (px, py) => ({
          x: m.a * px + m.c * py + m.e,
          y: m.b * px + m.d * py + m.f,
        });
        const corners = [
          at(x0, y0),
          at(x0 + w, y0),
          at(x0, y0 + h),
          at(x0 + w, y0 + h),
        ];
        const dpr = Math.min(window.devicePixelRatio || 1, 2);
        window.__labels.push({
          canvas: this.canvas?.id || '',
          text: String(text),
          size,
          x0: Math.min(...corners.map(c => c.x)) / dpr,
          x1: Math.max(...corners.map(c => c.x)) / dpr,
          y0: Math.min(...corners.map(c => c.y)) / dpr,
          y1: Math.max(...corners.map(c => c.y)) / dpr,
        });
      } catch {
        /* a measurement failure must not break the drawing */
      }
      return original.call(this, text, x, y, ...rest);
    };
  }
};

/**
 * The labels on the instrument canvas, as boxes in CSS pixels.
 *
 * The recorder has already resolved alignment, baseline, rotation and the
 * device-pixel scale, so what comes back here is where the text actually
 * landed on the picture the reader is looking at.
 */
async function labelsOn(page) {
  return page.evaluate(() => {
    const canvas = document.getElementById('investigationToolCanvas');
    const width = canvas?.clientWidth ?? 0;
    const height = canvas?.clientHeight ?? 0;
    const boxes = (window.__labels || []).filter(
      l => l.canvas === 'investigationToolCanvas' && l.text.trim()
    );
    return { width, height, boxes };
  });
}

/** Open the panel's step through the authoring preview and repaint it. */
async function openPanel(page, app, { lesson, step }) {
  await page.addInitScript(RECORDER);
  await app.boot({ url: `/?author=${lesson}&step=${step}` });
  await expect(page.locator('#investigationPanel')).toBeVisible();
  await expect(page.locator('#investigationToolCanvas')).toBeVisible();
  // A repaint with the recorder in place, and two frames for anything that
  // draws itself on a timer.
  await page.evaluate(() => {
    window.__labels = [];
    window.dispatchEvent(new Event('resize'));
  });
  await page.waitForTimeout(700);
}

test.describe('instrument labels are legible', () => {
  for (const panel of PANELS) {
    test(`${panel.widget}`, async ({ page, app }) => {
      await openPanel(page, app, panel);
      const { width, height, boxes } = await labelsOn(page);

      expect(boxes.length, 'the panel drew some text').toBeGreaterThan(0);

      // 1. Nothing below the shared floor. The floor is TYPE.MIN rather than
      // TYPE.TICK on purpose: thirteen widget families had settled on ten
      // pixels, and the brief was to get rid of the eight and nine pixel
      // labels, not to relay out fifty panels. New work uses TICK.
      const small = boxes
        .filter(b => b.size > 0 && b.size < TYPE.MIN)
        .map(b => `${b.size}px "${b.text.slice(0, 24)}"`);
      expect(small, 'labels below the shared floor').toEqual([]);

      // 2. Nothing drawn off the edge. A pixel of slack, because a centred
      // label on the last tick legitimately sits on the boundary.
      const off = boxes
        .filter(b => b.x0 < -1 || b.x1 > width + 1 || b.y1 > height + 1)
        .map(
          b =>
            `"${b.text.slice(0, 24)}" at ${Math.round(b.x0)},${Math.round(b.y0)}`
        );
      expect(off, `labels outside the ${width}x${height} canvas`).toEqual([]);

      // 3. No label on top of another. The tolerance is two pixels in each
      // direction: adjacent lines of a wrapped caption touch by a hair and
      // that is not what this is looking for.
      const hits = [];
      for (let i = 0; i < boxes.length; i++) {
        for (let j = i + 1; j < boxes.length; j++) {
          const a = boxes[i];
          const b = boxes[j];
          const dx = Math.min(a.x1, b.x1) - Math.max(a.x0, b.x0);
          const dy = Math.min(a.y1, b.y1) - Math.max(a.y0, b.y0);
          if (dx <= 2 || dy <= 2) continue;
          // Several panels draw a label twice - once in the background colour
          // as a halo and once in ink - so that it stays readable over a
          // filled shape. That is the technique working, not a collision.
          const sameText = a.text === b.text;
          const nearlyOnTopOfEachOther =
            Math.abs(a.x0 - b.x0) < 3 && Math.abs(a.y0 - b.y0) < 3;
          if (sameText && nearlyOnTopOfEachOther) continue;
          hits.push(`"${a.text.slice(0, 20)}" over "${b.text.slice(0, 20)}"`);
        }
      }
      expect(hits, 'labels drawn on top of each other').toEqual([]);
    });
  }
});
