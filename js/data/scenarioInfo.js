// =============================================================================
// Scenario catalog - the one place a built-in scenario is described
// -----------------------------------------------------------------------------
// Every built-in scenario by its public id, with its concept tags and
// thumbnail, and the assembly that puts each one's English title and summary
// back beside them.
//
// The id is the scenario's identity: lower-case and hyphenated, permanent, and
// what a share link, a lesson, a course pack, an experiment and the world
// golden name it by. A title is a translation of the id - the catalog entries
// scenario.<id>.title and .summary in js/i18n - and is never a key, so a title
// can be reworded without breaking anything that names the scenario.
//
// Until Roadmap II Prompt 63 the key was the English name ('Solar System'),
// and links, saved settings and files made before then still carry it.
// scenarioId() below reads either: each id is its old name lower-cased, with
// apostrophes dropped and every other run of spaces and punctuation one
// hyphen, so that rule is the alias map, and tests/scenarioIds.test.js holds it
// to all 59 old names. js/scenarios.js keeps the same rule for the engine,
// which never loads this module (it brings the English catalog with it).
//
// The prose lives in js/i18n/en.js, which keeps the rule this file has always
// had - exactly one copy of a scenario's title and summary in the application -
// while making the message catalog the single place a translator works.
// SCENARIO_INFO[id].title and .summary read as plain English, which is what
// the thumbnail generator, the instructor material builder and the catalog
// tests expect. The interface does not read them: js/i18n/scenario.js has
// scenarioTitle() and scenarioSummary(), which answer in the reader's language.
//
// tags       ids from js/data/scenarioTags.js, 1-4 per scenario, assigned by
//            hand. They answer "what could I teach with this?", which is not
//            the same question as "what objects are in it?".
// thumbnail  images/scenarios/<id>.webp, a capture of the scenario actually
//            running, regenerated by `npm run thumbnails`. See
//            tools/generate-scenario-thumbnails.mjs.
// =============================================================================

