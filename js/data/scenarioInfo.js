export const SCENARIO_INFO = Object.fromEntries(
  Object.entries(SCENARIO_STRUCTURE).map(([id, structure]) => [
    id,
    {
      // Falling back to the id rather than to an empty string: a scenario
      // added to the structure and forgotten in the catalog should show up
      // as its own id in the gallery, which is odd enough to be noticed and
      // harmless enough not to break the page.
      title: EN[`scenario.${id}.title`] ?? id,
      summary: EN[`scenario.${id}.summary`] ?? '',
      thumbnail: `images/scenarios/${id}.webp`,
      ...structure,
    },
  ])
);

/**
 * The public id of a built-in scenario, from its id or from the English name
 * it was keyed by before it had one.
 *
 * @param {*} key - An id, an old name ('Solar System'), or anything else
 * @returns {?string} The id, or null when it names no built-in scenario
 */
export const scenarioId = key => {
  if (typeof key !== 'string') return null;
  if (Object.hasOwn(SCENARIO_STRUCTURE, key)) return key;
  const id = key
    .toLowerCase()
    .replace(/'/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
  return Object.hasOwn(SCENARIO_STRUCTURE, id) ? id : null;
};
