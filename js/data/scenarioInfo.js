// =============================================================================
// Scenario catalog - the one place a built-in scenario is described
// -----------------------------------------------------------------------------
// Concept tags and thumbnail for every built-in scenario, and the assembly that
// puts each one's title and summary back beside them.
//
// The prose moved to js/i18n/en.js when the interface was internationalized.
// That keeps the rule this file has always had - there is exactly one copy of a
// scenario's title and summary anywhere in the application - while making the
// message catalogue the single place a translator works. The shape exported
// here is unchanged: SCENARIO_INFO[key].title and .summary still read as plain
// English strings, which is what the thumbnail generator, the instructor
// material builder and the catalog tests expect of them.
//
// Those two properties are English. The interface does not read them directly:
// js/i18n/scenario.js has scenarioTitle() and scenarioSummary(), which go
// through t() and answer in the reader's language. English here is the
// identifier-shaped form used by tooling and by the search index's fallback.
//
// tags       ids from js/data/scenarioTags.js, 1-4 per scenario, assigned by
//            hand. They answer "what could I teach with this?", which is not
//            the same question as "what objects are in it?".
// thumbnail  a capture of the scenario actually running, regenerated by
//            `npm run thumbnails`. See tools/generate-scenario-thumbnails.mjs.
// =============================================================================

