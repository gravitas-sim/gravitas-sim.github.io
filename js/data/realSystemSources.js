// =============================================================================
// Where the real systems' numbers come from
// -----------------------------------------------------------------------------
// Every real-system parameter object in Gravitas - a planet, a star, a small
// body, a system - has its sources here: [{text, doi | bibcode | url, fields}],
// each source and the fields it gives. A value no cited table gives is listed
// under UNSOURCED, "approximate, unsourced", rather than credited to a source
// that does not give it; a unit or a choice a scenario makes is NOT_MEASURED.
// One entry may leave out `fields`: it gives every value the others do not
// name.
//
// They are kept beside the objects rather than on them, keyed by where each
// object is, for one reason: bytes. The objects are in js/data/exoplanetSystems.js,
// js/data/trappist1.js and the tables of js/world/build.js, which the sandbox,
// every lesson and the experiment runner load, and whose routes had under a
// kilobyte and no request to spare (tools/route-budgets.json). Nothing in the
// application imports this module, so it is in no bundle and no route: the
// tools read it, and the provenance line carries a one-line summary of it
// (SCENARIO_SOURCES in js/ui.js, held to it by tests/realSystemSources.test.js).
//
// - The author check's attribution rule (tools/authoring/realSystems.mjs)
//   requires an entry for every object, naming every value on it, and refuses
//   an entry for an object that is not there.
// - tools/data-packs/compilations.mjs holds the compiled modules' entries to
//   the pinned tables each value was found in.
// - The model page lists them all (model/index.html, generated by
//   tools/docs-facts.mjs), and a captured frame's provenance line prints a
//   scenario's in a line (js/ui.js).
//
// The values of js/world/build.js were compared with these sources on
// 2026-10-01: each planet with NASA's fact sheet for it, each semi-major axis
// with JPL's mean planetary elements, and each small body with the JPL
// Small-Body Database. A value is cited only when it is the published one
// rounded to the digits it keeps.
//
// Content only, no imports, in the same spirit as the rest of js/data.
// =============================================================================

