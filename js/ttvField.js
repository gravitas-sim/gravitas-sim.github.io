// =============================================================================
// The views of the transit-timing panels (Prompt 226, TTV.md)
// -----------------------------------------------------------------------------
// Pure functions of the panels' control values, shared by js/ttvWidgets.js and
// tests/ttvLessons.test.js (which recomputes every number a lesson states from
// them). Nothing is calculated here that the kernel does not (js/kernels/ttv/): the
// template fit that measures a transit time, the straight-line ephemeris, the
// super-period scan and the cited relations.
//
// The data are SYNTHETIC: three two-planet systems integrated by the engine, each transit
// a noisy window of light curve measured by the kernel (js/data/ttvPack.js, generated by
// tools/ttv-pack.mjs). No star was observed (TTV.md, "Data").
//
// Pure: no DOM, no clock.
// =============================================================================

import { TTV_PACK } from './data/ttvPack.js';
import {
  analyseTransitTimes,
  deltaOf,
  fitSinusoidAt,
  linearEphemeris,
  measureTransitTime,
  superPeriod,
  transitWindow,
  ttvAmplitudes,
  relationDomain,
  MIN_CYCLES,
} from './kernels/ttv/index.js';

const { Math, Map } = globalThis;

const clamp = (x, lo, hi) => Math.max(lo, Math.min(hi, x));
const caches = new Map();
const memo = (key, make) => {
  if (!caches.has(key)) caches.set(key, make());
  return caches.get(key);
};
const MIN_PER_DAY = 1440;

/** The three systems, in the order of the panels' system control. */
export const SYSTEM_IDS = Object.freeze(['S1', 'S2', 'S3']);
/** The noise of a window the transit panel makes, in ppm per 2-minute point. */
export const NOISES_PPM = Object.freeze([100, 400, 1600]);
/** The mass ratio of one Earth to the Sun, to turn a ratio into Earth masses. */
export const EARTH_PER_SUN = 332946.0487;

const systemOf = v => {
  const i = clamp(Math.round(v.system ?? 0), 0, 2);
  return { index: i, id: SYSTEM_IDS[i], data: TTV_PACK.systems[SYSTEM_IDS[i]] };
};

/** The mean periods, ephemerides and the relation's super-period of a system's pinned times. */
export function pairOf(index) {
  return memo(`pair:${index}`, () => {
    const id = SYSTEM_IDS[index];
    const sys = TTV_PACK.systems[id];
    const eph = sys.planets.map(p => linearEphemeris(p.n, p.time, p.sigma));
    const ps = superPeriod(eph[0].P, eph[1].P, sys.j);
    const delta = deltaOf(eph[0].P, eph[1].P, sys.j);
    const rel = ttvAmplitudes({
      P1: eph[0].P,
      P2: eph[1].P,
      mu1: sys.planets[0].mu,
      mu2: sys.planets[1].mu,
      j: sys.j,
    });
    return { id, sys, eph, superPeriod: ps, delta, relation: rel };
  });
}

// ---- the transit panel ------------------------------------------------------------

/**
 * One transit's window and its template fit.
 * @param {{system?: number, planet?: number, transit?: number, noise?: number, view?: number}} v
 */
export function transitView(v) {
  const { index, id, data } = systemOf(v);
  const planet = Math.round(v.planet ?? 0) === 1 ? 1 : 0;
  const p = data.planets[planet];
  const k = clamp(Math.round(v.transit ?? 0), 0, p.n.length - 1);
  const noiseIndex = clamp(Math.round(v.noise ?? 0), 0, NOISES_PPM.length - 1);
  const sigmaPpm = NOISES_PPM[noiseIndex];
  return memo(`transit:${index}:${planet}:${k}:${noiseIndex}`, () => {
    const lc = TTV_PACK.lightCurve;
    const template = {
      P: p.P,
      k: lc.k,
      aRs: lc.aRs,
      b: lc.b,
      q1: lc.q1,
      q2: lc.q2,
    };
    const eph = pairOf(index).eph[planet];
    const guess = eph.T0 + p.n[k] * eph.P;
    const w = transitWindow({
      trueTime: p.truth[k],
      center: guess,
      template,
      sigma: sigmaPpm * 1e-6,
      cadence: lc.cadence_d,
      halfWidth: lc.window_halfwidth_d,
      seed: 'ttv-panel-226',
      labels: [id, planet, p.n[k], noiseIndex],
    });
    const m = measureTransitTime({
      t: w.t,
      flux: w.flux,
      sigma: w.sigma,
      template,
      guess,
    });
    const curve = [];
    if (m.status === 'ok') {
      const model = transitWindow({
        trueTime: m.time,
        center: guess,
        template,
        sigma: 0,
        cadence: lc.cadence_d,
        halfWidth: lc.window_halfwidth_d,
        seed: 'x',
      });
      for (let i = 0; i < model.t.length; i++)
        curve.push([model.t[i], model.flux[i] * m.baseline]);
    }
    // chi-square as the mid-time is moved, in minutes about the fit
    const profile = [];
    if (m.status === 'ok') {
      for (let s = -12; s <= 12; s++) {
        const dt = s * m.sigma * 0.5;
        const trial = transitWindow({
          trueTime: m.time + dt,
          center: guess,
          template,
          sigma: 0,
          cadence: lc.cadence_d,
          halfWidth: lc.window_halfwidth_d,
          seed: 'x',
        });
        let chi2 = 0;
        for (let i = 0; i < trial.t.length; i++)
          chi2 += ((w.flux[i] - trial.flux[i] * m.baseline) / w.sigma) ** 2;
        profile.push([dt * MIN_PER_DAY, chi2 - m.chi2]);
      }
    }
    return {
      system: id,
      planet,
      transit: p.n[k],
      count: p.n.length,
      sigmaPpm,
      window: w,
      fit: m,
      guess,
      curve,
      profile,
      trueTime: p.truth[k],
      errorMinutes:
        m.status === 'ok' ? (m.time - p.truth[k]) * MIN_PER_DAY : NaN,
      sigmaMinutes: m.status === 'ok' ? m.sigma * MIN_PER_DAY : NaN,
      view: Math.round(v.view ?? 0) === 1 ? 1 : 0,
    };
  });
}

// ---- the timing panel -------------------------------------------------------------

/**
 * The O-C diagram of a system's pinned measured times and its analysis.
 * @param {{system?: number, planet?: number, span?: number, view?: number}} v
 *   span: the percentage of the record shown (the earliest transits); view 0 the O-C,
 *   1 the chi-square against trial period
 */
export function timingView(v) {
  const { index, id, data } = systemOf(v);
  const planet = Math.round(v.planet ?? 0) === 1 ? 1 : 0;
  const span = clamp(Math.round(v.span ?? 100), 20, 100);
  return memo(`timing:${index}:${planet}:${span}`, () => {
    const pair = pairOf(index);
    const p = data.planets[planet];
    const cut =
      p.time[0] + (span / 100) * (p.time[p.time.length - 1] - p.time[0]);
    const keep = p.time.map((t, i) => (t <= cut ? i : -1)).filter(i => i >= 0);
    const n = keep.map(i => p.n[i]);
    const t = keep.map(i => p.time[i]);
    const s = keep.map(i => p.sigma[i]);
    const an = analyseTransitTimes({
      epochs: n,
      times: t,
      sigmas: s,
      expectedPeriod: pair.superPeriod,
    });
    const eph = an.ephemeris;
    const oc =
      eph.status === 'ok'
        ? Array.from(eph.oc, (x, i) => [
            n[i],
            x * MIN_PER_DAY,
            s[i] * MIN_PER_DAY,
          ])
        : [];
    let model = [];
    let amplitudeAtRelation = NaN;
    if (an.superPeriod) {
      const fit = fitSinusoidAt(n, t, s, an.superPeriod.value);
      model = n.map((q, i) => [
        q,
        (fit.coef[0] +
          fit.coef[1] * q +
          fit.coef[2] * Math.cos((2 * Math.PI * t[i]) / fit.period) +
          fit.coef[3] * Math.sin((2 * Math.PI * t[i]) / fit.period) -
          (eph.T0 + q * eph.P)) *
          MIN_PER_DAY,
      ]);
    }
    if (pair.relation.status === 'ok') {
      const fr = fitSinusoidAt(n, t, s, pair.superPeriod);
      if (fr) amplitudeAtRelation = Math.hypot(fr.A, fr.B);
    }
    return {
      system: id,
      planet,
      span,
      count: n.length,
      analysis: an,
      oc,
      model,
      pair,
      amplitudeAtRelationMinutes: amplitudeAtRelation * MIN_PER_DAY,
      relationAmplitudeMinutes:
        pair.relation.status === 'ok'
          ? (planet
              ? pair.relation.outer.amplitude
              : pair.relation.inner.amplitude) * MIN_PER_DAY
          : NaN,
      view: Math.round(v.view ?? 0) === 1 ? 1 : 0,
      minCycles: MIN_CYCLES,
      domain: relationDomain({
        P1: pair.eph[0].P,
        P2: pair.eph[1].P,
        mu1: data.planets[0].mu,
        mu2: data.planets[1].mu,
        j: data.j,
      }),
    };
  });
}
