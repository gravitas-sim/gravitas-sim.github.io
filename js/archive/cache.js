// =============================================================================
// A cached archive answer never pretends to be a new one
// -----------------------------------------------------------------------------
// An answer is kept by its query URL, with the time it was retrieved, the
// SHA-256 of its bytes and the digest of its content. Three rules follow from
// what a reader must be able to trust:
//
//   - A fresh copy (younger than a week) is used as it is, and says so.
//   - An old copy is refreshed. If the archive cannot be reached, the old
//     copy is offered as STALE, with its age and the reason, never silently.
//   - A refreshed answer whose content differs is a different observation:
//     its id carries the content digest, so a figure made from the old answer
//     still names the old one, and `changed` tells the page to say so.
//     Content, not bytes: VizieR stamps every answer with the time it was
//     asked, so the bytes differ on every request.
//
// No lesson reads this. Lessons read curated packs, which are part of the site
// and work offline; this serves only the Observatory's opt-in import. The
// store is the reader's own IndexedDB, and nothing in it leaves the device.
// =============================================================================

import { sha256Hex } from './net.js';

export const FRESH_MS = 7 * 86_400_000;

/**
 * @param {string} key - The query URL
 * @param {() => Promise<{bytes: Uint8Array, url: string}>} load - The network
 * @param {{store: {get: Function, set: Function},
 *   identify: (bytes: Uint8Array) => Promise<string>, maxAgeMs?: number,
 *   now?: () => number}} opts - `identify` gives the content digest
 * @returns {Promise<{bytes: Uint8Array, url: string, sha256: string,
 *   identity: string, retrievedMs: number, from: 'cache'|'network',
 *   ageMs: number, stale: boolean, changed: boolean, error?: Error,
 *   previous?: object|null}>}
 */
export async function cachedFetch(
  key,
  load,
  { store, identify, maxAgeMs = FRESH_MS, now = Date.now }
) {
  let held = null;
  try {
    held = (await store.get(key)) ?? null;
  } catch {
    held = null; // an unreadable store is an empty one
  }
  const age = held ? now() - held.retrievedMs : null;
  if (held && age >= 0 && age < maxAgeMs)
    return { ...held, from: 'cache', ageMs: age, stale: false, changed: false };
  let got;
  try {
    got = await load();
  } catch (error) {
    if (!held || error?.code === 'canceled') throw error;
    return {
      ...held,
      from: 'cache',
      ageMs: age,
      stale: true,
      changed: false,
      error,
    };
  }
  const entry = {
    bytes: got.bytes,
    url: got.url,
    sha256: await sha256Hex(got.bytes),
    identity: await identify(got.bytes),
    retrievedMs: now(),
  };
  try {
    await store.set(key, entry);
  } catch {
    /* a full or private store: the answer is still good, just not kept */
  }
  return {
    ...entry,
    from: 'network',
    ageMs: 0,
    stale: false,
    changed: Boolean(held && held.identity !== entry.identity),
    previous: held
      ? {
          sha256: held.sha256,
          identity: held.identity,
          retrievedMs: held.retrievedMs,
        }
      : null,
  };
}

// What the archive cache may hold before it makes room (Prompt 147). These are
// cached copies of public answers, regenerated by asking again, so they are
// the first thing to go. Durable student work is not in this database
// (STORAGE.md's matrix) and nothing here ever touches it.
export const LIMITS = { maxBytes: 64 * 1024 * 1024, maxEntries: 400 };

const sizeOf = v => v?.bytes?.byteLength ?? v?.bytes?.length ?? 0;

/**
 * The keys to drop, least recently used first, until the rest fits.
 * @param {Array<{key: *, usedMs: number, size: number}>} rows
 * @param {{maxBytes: number, maxEntries: number}} limits
 * @returns {Array<*>} Keys to delete
 */
export function victims(rows, { maxBytes, maxEntries }) {
  const byUse = [...rows].sort((a, b) => a.usedMs - b.usedMs);
  let bytes = rows.reduce((n, r) => n + r.size, 0);
  let count = rows.length;
  const out = [];
  for (const r of byUse) {
    if (bytes <= maxBytes && count <= maxEntries) break;
    out.push(r.key);
    bytes -= r.size;
    count--;
  }
  return out;
}

/** A Map as a store: for tests, and for a page with no IndexedDB. */
export function memoryStore(limits = LIMITS, now = Date.now) {
  const m = new Map();
  const rows = () =>
    [...m].map(([key, v]) => ({
      key,
      usedMs: v.usedMs,
      size: sizeOf(v.value),
    }));
  return {
    get: async k => {
      const hit = m.get(k);
      if (hit) hit.usedMs = now();
      return hit?.value;
    },
    set: async (k, v) => {
      m.set(k, { value: v, usedMs: now() });
      for (const key of victims(rows(), limits)) m.delete(key);
    },
    usage: async () => ({
      entries: m.size,
      bytes: rows().reduce((n, r) => n + r.size, 0),
    }),
    clear: async () => m.clear(),
  };
}

/**
 * The reader's IndexedDB as a store, one database of its own. Falls back to
 * memory where IndexedDB is missing or refused (a private window, some
 * embedded browsers).
 */
export function idbStore(name = 'gravitas-archive', limits = LIMITS) {
  if (typeof indexedDB === 'undefined') return memoryStore(limits);
  let opening = null;
  const db = () =>
    (opening ??= new Promise((resolve, reject) => {
      const req = indexedDB.open(name, 1);
      req.onupgradeneeded = () => req.result.createObjectStore('answers');
      req.onsuccess = () => resolve(req.result);
      req.onerror = () => {
        opening = null; // a refused open is retried by the next call
        reject(req.error);
      };
    }));
  const run = (mode, fn) =>
    db().then(
      d =>
        new Promise((resolve, reject) => {
          const tx = d.transaction('answers', mode);
          const req = fn(tx.objectStore('answers'));
          tx.oncomplete = () => resolve(req.result);
          tx.onerror = () => reject(tx.error);
          tx.onabort = () => reject(tx.error);
        })
    );
  // Each row is { value, usedMs }: the answer and when it was last read or
  // written, which is what eviction orders by. A row an older build wrote (the
  // bare answer) has no usedMs and counts as the oldest.
  const unwrap = r => (r && 'usedMs' in r && 'value' in r ? r.value : r);
  const listRows = () =>
    db().then(
      d =>
        new Promise((resolve, reject) => {
          const out = [];
          const tx = d.transaction('answers', 'readonly');
          const req = tx.objectStore('answers').openCursor();
          req.onsuccess = () => {
            const c = req.result;
            if (!c) return;
            out.push({
              key: c.key,
              usedMs: c.value?.usedMs ?? 0,
              size: sizeOf(unwrap(c.value)),
            });
            c.continue();
          };
          tx.oncomplete = () => resolve(out);
          tx.onerror = () => reject(tx.error);
          tx.onabort = () => reject(tx.error);
        })
    );
  const evict = async () => {
    const drop = victims(await listRows(), limits);
    for (const key of drop) await run('readwrite', s => s.delete(key));
  };
  return {
    // The cache is an optimisation: a database the browser refuses is a miss
    // and a skipped write, never a failed query.
    get: async key => {
      const row = await run('readonly', s => s.get(key)).catch(() => undefined);
      if (row && 'usedMs' in row && 'value' in row)
        run('readwrite', s => s.put({ ...row, usedMs: Date.now() }, key)).catch(
          () => {}
        );
      return unwrap(row);
    },
    set: (key, value) =>
      run('readwrite', s => s.put({ value, usedMs: Date.now() }, key))
        .then(evict)
        .then(
          () => {},
          () => {}
        ),
    usage: async () => {
      try {
        const r = await listRows();
        return { entries: r.length, bytes: r.reduce((n, x) => n + x.size, 0) };
      } catch {
        return { entries: 0, bytes: 0 };
      }
    },
    clear: () =>
      run('readwrite', s => s.clear()).then(
        () => {},
        () => {}
      ),
  };
}
