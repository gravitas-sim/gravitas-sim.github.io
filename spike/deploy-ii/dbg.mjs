import { spawn } from 'node:child_process';
import path from 'node:path';
import { setTimeout as sleep } from 'node:timers/promises';
import { chromium } from 'playwright';
const root = process.argv[2]; const offline = process.argv[3] === 'offline';
const server = spawn(process.execPath, ['tools/static-server.mjs', '--root', root, '--port', '4481'], { stdio: 'ignore' });
await sleep(1500);
const b = await chromium.launch(); const ctx = await b.newContext({ serviceWorkers: 'allow' });
await ctx.addInitScript(() => { try { localStorage.setItem('gravitas_welcome_seen_v1', '1'); } catch {} });
const page = await ctx.newPage();
const logs = []; page.on('console', m => logs.push(m.type() + ': ' + m.text().slice(0, 150))); page.on('pageerror', e => logs.push('pageerror ' + e.message.slice(0, 150)));
page.on('requestfailed', r => logs.push('failed ' + r.url()));
await page.goto('http://127.0.0.1:4481/#investigation=keplers-laws');
await page.waitForFunction(() => { const p = document.getElementById('investigationPanel'); const t = document.getElementById('investigationTitle'); return p && !p.hidden && t?.textContent.trim(); }, null, { timeout: 30000 }).then(() => console.log('online lesson ok')).catch(() => console.log('online lesson NOT ok'));
await page.waitForFunction(() => navigator.serviceWorker.controller || true);
await page.evaluate(async () => { const r = await navigator.serviceWorker.ready; return r.active.state; });
await sleep(8000);
if (offline) await ctx.setOffline(true);
await page.reload({ waitUntil: 'domcontentloaded' });
const ok = await page.waitForFunction(() => { const p = document.getElementById('investigationPanel'); const t = document.getElementById('investigationTitle'); return p && !p.hidden && t?.textContent.trim(); }, null, { timeout: 30000 }).then(() => 'reload lesson ok').catch(() => 'reload lesson NOT ok');
console.log(ok, page.url()); console.log(logs.slice(0, 12).join('\n'));
await b.close(); server.kill();
