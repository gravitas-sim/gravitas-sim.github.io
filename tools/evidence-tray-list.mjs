#!/usr/bin/env node
// =============================================================================
// Which written answers carry an evidence tray, as a table
// -----------------------------------------------------------------------------
//   node tools/evidence-tray-list.mjs           write docs/evidence-tray.md
//   node tools/evidence-tray-list.mjs --check   exit 1 if the file is stale
//
// One row per short-answer step. The tray beside the answer box offers the
// readings the measure steps before it take (by step and field) and the
// predictions whose reveal comes before it; a step that `js/investigations/trayCites.js` names narrows
// both to those steps. The rule is `citable` in js/investigations/evidence.js,
// the one the lesson itself runs, so the table and the screen cannot differ.
// A step with nothing to offer has no tray.
// =============================================================================

import { readFile, writeFile } from 'node:fs/promises';
import { INVESTIGATIONS } from '../js/data/investigations.js';
import { citable } from '../js/investigations/evidence.js';
import { CITES } from '../js/investigations/trayCites.js';

const OUT = new URL('../docs/evidence-tray.md', import.meta.url);

/** `sid (n)` for each step that contributes readings, in lesson order. */
const byStep = readings => {
  const n = new Map();
  for (const r of readings) n.set(r.step, (n.get(r.step) || 0) + 1);
  return [...n].map(([sid, k]) => `${sid} (${k})`).join(', ');
};

/**
 * Every short-answer step with what its tray offers.
 * @returns {Array<object>} Rows: lesson, index, sid, reflect, cite, readings, predictions
 */
export function trayRows() {
  const rows = [];
  for (const inv of INVESTIGATIONS)
    inv.steps.forEach((step, i) => {
      if (step.kind !== 'short') return;
      const { readings, predictions } = citable(
        inv.steps,
        step,
        CITES[inv.id]?.[step.sid]
      );
      rows.push({
        lesson: inv.id,
        index: i + 1,
        sid: step.sid,
        reflect: Boolean(step.reflect),
        cite: Boolean(CITES[inv.id]?.[step.sid]),
        readings,
        predictions,
      });
    });
  return rows;
}

/**
 * The lessons with a held prediction and no written answer after its result: the loops that end without the
 * student's words. A list to read, not a rule: whether a comparison teaches enough to ask for an explanation is
 * a judgement made lesson by lesson.
 * @returns {Array<{lesson: string, loops: number, estimates: number}>}
 */
export function openLoops() {
  const out = [];
  for (const inv of INVESTIGATIONS) {
    const loops = inv.steps.filter(s => s.type === 'predict' && s.reveal);
    const last = Math.max(
      -1,
      ...loops.map(s => inv.steps.findIndex(r => r.sid === s.reveal))
    );
    if (loops.length && !inv.steps.slice(last).some(s => s.kind === 'short'))
      out.push({
        lesson: inv.id,
        loops: loops.length,
        estimates: loops.filter(s => s.kind === 'estimate').length,
      });
  }
  return out;
}

/** The table, as the file holds it. */
export function render(rows = trayRows(), loops = openLoops()) {
  const withTray = rows.filter(r => r.readings.length || r.predictions.length);
  const head = [
    '# Written answers and their evidence tray',
    '',
    'GENERATED by `node tools/evidence-tray-list.mjs`; do not edit. The rule is',
    '`citable` in `js/investigations/evidence.js`: a short-answer step offers the',
    'readings the measure steps before it take (each field that holds a number the',
    'student read or typed, not a derived one) and the predictions whose reveal',
    "comes before it. A step that `js/investigations/trayCites.js` names offers only those steps'. The tray",
    'is read-only, holds only what the student produced, shows a prediction only',
    'after its reveal and never prints an authored answer.',
    '',
    `${rows.length} short-answer steps in ${new Set(rows.map(r => r.lesson)).size} lessons; ${withTray.length} carry a tray, ` +
      `${rows.length - withTray.length} have nothing to offer. ${rows.filter(r => r.cite).length} are narrowed by \`trayCites.js\`.`,
    '',
    '| Lesson | Step | Id | Reflection | Narrowed | Readings | Reading steps | Predictions |',
    '|---|---|---|---|---|---|---|---|',
  ];
  const body = rows.map(
    r =>
      `| ${r.lesson} | ${r.index} | ${r.sid} | ${r.reflect ? 'yes' : ''} | ${r.cite ? 'yes' : ''} | ` +
      `${r.readings.length} | ${byStep(r.readings) || 'none'} | ` +
      `${r.predictions.map(p => `${p.step} (revealed at ${p.reveal})`).join(', ') || 'none'} |`
  );
  const tail = [
    '',
    '## Prediction loops that end without a written answer',
    '',
    'Lessons whose last held prediction is revealed after (or without) any',
    'short-answer step. Each is a candidate for a closing step in the',
    "student's words; none has one yet. `estimate` counts the loops that",
    'compare a number the student committed with the one they read.',
    '',
    '| Lesson | Held predictions | Estimates |',
    '|---|---|---|',
    ...loops.map(l => `| ${l.lesson} | ${l.loops} | ${l.estimates} |`),
  ];
  return [...head, ...body, ...tail, ''].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = render();
  if (process.argv.includes('--check')) {
    const have = await readFile(OUT, 'utf8').catch(() => '');
    if (have !== text) {
      console.error(
        'docs/evidence-tray.md is stale: run node tools/evidence-tray-list.mjs'
      );
      process.exit(1);
    }
    console.log('docs/evidence-tray.md is current');
  } else {
    await writeFile(OUT, text);
    console.log(
      `wrote docs/evidence-tray.md (${text.split('\n').length} lines)`
    );
  }
}
