#!/usr/bin/env node
// =============================================================================
// The oracle's input frames and cases (Prompt 180)
// -----------------------------------------------------------------------------
//   node tools/photometry-oracle/make-inputs.mjs <out.json>
//
// Detector-kernel frames of fixed seeds (js/kernels/detector/frame.js, a clean
// detector, bias subtracted, in whole ADU), and the apertures and centroid
// starts the oracle (oracle.py: photutils) and the tests both measure. The
// frames are written into the fixture, so the oracle and the tests read the
// same pixels and nothing here is regenerated by a test. The truth of every
// synthetic star is in `truth` (the frame's manifest).
// =============================================================================

import { Buffer } from 'node:buffer';
import { writeFileSync } from 'node:fs';
import process from 'node:process';
import { simulateFrame } from '../../js/kernels/detector/frame.js';

const DETECTOR = {
  width: 64,
  height: 64,
  gain: 1.5,
  readNoise: 8,
  biasLevel: 500,
  biasColumnSigma: 0,
  darkRate: 0,
  hotFraction: 0,
  qeScatter: 0,
  vignette: 0,
  dustCount: 0,
  cosmicRate: 0,
  fullWell: 100000,
};
const EXPOSURE = 30;

const SPECS = [
  {
    id: 'two-stars',
    fwhm: 3,
    sources: [
      { x: 24.37, y: 30.82, rate: 400 },
      { x: 41.64, y: 35.11, rate: 90 },
    ],
  },
  {
    id: 'gradient',
    fwhm: 3,
    sources: [{ x: 32.41, y: 31.73, rate: 300 }],
    plane: { x: 0.5, y: -0.3 },
  },
  { id: 'wide', fwhm: 4.5, sources: [{ x: 31.27, y: 33.58, rate: 800 }] },
  {
    id: 'three-bright',
    fwhm: 3,
    sources: [
      { x: 20.55, y: 21.3, rate: 3000 },
      { x: 44.18, y: 22.9, rate: 1500 },
      { x: 33.02, y: 45.46, rate: 2200 },
    ],
  },
  {
    id: 'outliers',
    fwhm: 3,
    sources: [{ x: 30.66, y: 34.2, rate: 350 }],
    hot: [
      { x: 41, y: 31, adu: 3000 },
      { x: 22, y: 36, adu: 2400 },
      { x: 33, y: 20, adu: 1800 },
    ],
  },
];

const frames = SPECS.map(s => {
  const f = simulateFrame({
    seed: `photometry-180-oracle-${s.id}`,
    exposure: EXPOSURE,
    detector: { ...DETECTOR, fwhm: s.fwhm },
    scene: { sky: 3, sources: s.sources },
  });
  const W = f.width;
  const adu = Int16Array.from(f.values, v => v - DETECTOR.biasLevel);
  if (s.plane)
    for (let j = 0; j < W; j++)
      for (let i = 0; i < W; i++)
        adu[j * W + i] += Math.round(
          s.plane.x * (i - 31.5) + s.plane.y * (j - 31.5)
        );
  for (const h of s.hot ?? []) adu[h.y * W + h.x] += h.adu;
  return {
    id: s.id,
    width: W,
    height: f.height,
    fwhm: s.fwhm,
    adu: Buffer.from(adu.buffer).toString('base64'),
    truth: { sources: s.sources, exposure: EXPOSURE, plane: s.plane ?? null },
  };
});

// Apertures: positions near the stars and near empty sky, radii that are not
// round numbers so no pixel centre lies on a circle's edge.
const CASES = [
  ['two-stars', 24.4, 30.8, 4.6, 8.9, 14.3],
  ['two-stars', 24.1, 31.2, 3.1, 8.9, 14.3],
  ['two-stars', 41.6, 35.1, 4.55, 9.3, 15.1],
  ['two-stars', 41.9, 34.7, 6.7, 10.7, 16.3],
  ['two-stars', 32.7, 12.4, 4.4, 8.7, 13.9],
  ['gradient', 32.4, 31.7, 4.5, 9.1, 15.2],
  ['gradient', 32.8, 31.3, 5.35, 9.1, 15.2],
  ['gradient', 32.4, 31.7, 4.5, 10.3, 17.7],
  ['gradient', 10.2, 51.6, 3.4, 7.7, 12.1],
  ['wide', 31.3, 33.6, 6.8, 11.9, 17.3],
  ['wide', 31.6, 33.2, 4.3, 11.9, 17.3],
  ['wide', 31.3, 33.6, 9.2, 13.1, 18.9],
  ['three-bright', 20.6, 21.3, 4.45, 8.85, 14.15],
  ['three-bright', 44.2, 22.9, 4.45, 8.85, 14.15],
  ['three-bright', 33.0, 45.5, 4.45, 8.85, 14.15],
  ['three-bright', 33.2, 45.1, 2.45, 8.85, 14.15],
  ['outliers', 30.7, 34.2, 4.5, 9.0, 15.0],
  ['outliers', 30.9, 33.9, 5.5, 9.4, 15.6],
  ['outliers', 30.7, 34.2, 4.5, 11.0, 16.0],
].map(([frame, x, y, r, rIn, rOut]) => ({ frame, x, y, r, rIn, rOut }));

// Centroid starts: a whole-pixel start near each star, the half width of the
// window and, for the Gaussian-weighted centroid, the weight's sigma.
const CENTROIDS = [
  ['two-stars', 24, 31, 6, 1.27, 8.9, 14.3],
  ['two-stars', 42, 35, 6, 1.27, 9.3, 15.1],
  ['gradient', 32, 32, 6, 1.27, 9.1, 15.2],
  ['wide', 31, 34, 9, 1.91, 11.9, 17.3],
  ['three-bright', 21, 21, 6, 1.27, 8.85, 14.15],
  ['three-bright', 44, 23, 6, 1.27, 8.85, 14.15],
  ['three-bright', 33, 45, 6, 1.27, 8.85, 14.15],
  ['outliers', 31, 34, 6, 1.27, 9.0, 15.0],
].map(([frame, x0, y0, half, sigmaW, rIn, rOut]) => ({
  frame,
  x0,
  y0,
  half,
  sigmaW,
  rIn,
  rOut,
}));

const doc = {
  format: 'gravitas.photometry-oracle-inputs/1',
  convention:
    'pixel (0, 0) is the centre of the first pixel, x along a row; frames are bias-subtracted ADU (int16 little-endian, base64) times the gain make electrons; the variance plane is max(electrons, 0) + readNoise^2',
  gain: DETECTOR.gain,
  readNoise: DETECTOR.readNoise,
  clip: { sigma: 3, maxiters: 4 },
  frames,
  cases: CASES,
  centroids: CENTROIDS,
};
writeFileSync(process.argv[2], JSON.stringify(doc) + '\n');
process.stdout.write(
  `wrote ${process.argv[2]}: ${frames.length} frames, ${CASES.length} apertures, ${CENTROIDS.length} centroids\n`
);
