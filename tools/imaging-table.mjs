#!/usr/bin/env node
// =============================================================================
// Rebuild js/data/imagedPlanets.js from the pinned NASA Exoplanet Archive CSV
// -----------------------------------------------------------------------------
//   node tools/imaging-table.mjs /path/to/imaging.csv
//
// The CSV is the archive's TAP answer to
//   select pl_name,hostname,sy_dist,sy_disterr1,sy_disterr2,pl_orbsmax,pl_orbsmaxerr1,pl_orbsmaxerr2,
//          pl_orbper,pl_bmassj,pl_bmassjerr1,pl_bmassjerr2,pl_radj,pl_eqt,st_teff,st_rad,sy_vmag,
//          sy_kmag,discoverymethod,disc_year from pscomppars where discoverymethod='Imaging' order by pl_name
// fetched by the coordinator on 2026-10-31 (the reference columns were rejected by the
// archive and are not recorded). The file is not in the repository; its SHA-256 is.
// =============================================================================

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

export const CSV_SHA256 =
  'cd0278850ca8a25f368c9f8c5708f8c01396538900222931668895cbe3beb805';
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'js/data/imagedPlanets.js');

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = '';
  let quoted = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    if (quoted) {
      if (ch === '"' && text[i + 1] === '"') ((cell += '"'), i++);
      else if (ch === '"') quoted = false;
      else cell += ch;
    } else if (ch === '"') quoted = true;
    else if (ch === ',') (row.push(cell), (cell = ''));
    else if (ch === '\n' || ch === '\r') {
      if (ch === '\r' && text[i + 1] === '\n') i++;
      row.push(cell);
      if (row.length > 1 || row[0] !== '') rows.push(row);
      row = [];
      cell = '';
    } else cell += ch;
  }
  if (cell !== '' || row.length) (row.push(cell), rows.push(row));
  return rows;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const file = process.argv[2];
  if (!file) throw new Error('usage: node tools/imaging-table.mjs imaging.csv');
  const bytes = readFileSync(file);
  const sha = createHash('sha256').update(bytes).digest('hex');
  if (sha !== CSV_SHA256)
    throw new Error(`the CSV is not the pinned file (sha256 ${sha})`);
  const [head, ...body] = parseCsv(bytes.toString('utf8'));
  const col = Object.fromEntries(head.map((h, i) => [h, i]));
  const n = (r, k) => {
    const s = (r[col[k]] ?? '').trim();
    return s === '' ? null : Number(s);
  };
  // [name, host, distance pc, a AU, mass Mjup, radius Rjup, temperature K, star Teff K, star radius Rsun, K mag, year]
  const rows = body.map(r => [
    r[col.pl_name],
    r[col.hostname],
    n(r, 'sy_dist'),
    n(r, 'pl_orbsmax'),
    n(r, 'pl_bmassj'),
    n(r, 'pl_radj'),
    n(r, 'pl_eqt'),
    n(r, 'st_teff'),
    n(r, 'st_rad'),
    n(r, 'sy_kmag'),
    n(r, 'disc_year'),
  ]);
  const prettier = await import('prettier');
  const source = `// GENERATED by tools/imaging-table.mjs; do not edit. The imaged planets of the NASA Exoplanet Archive's
// Planetary Systems Composite table (pscomppars, discoverymethod = 'Imaging'), retrieved 2026-10-31
// (${rows.length} rows; the archive's CSV has SHA-256 ${CSV_SHA256}). Public archive, credit requested;
// the archive's terms page was not read and the per-row reference columns were not retrieved (D-R10-230-03).
// Columns: name, host, distance (pc), semi-major axis (AU), mass (M_Jup), radius (R_Jup), the archive's
// temperature column (K; for these planets not an irradiation equilibrium), star Teff (K), star radius (R_Sun),
// K magnitude, discovery year. null is a blank cell.
export const IMAGED_COLUMNS = ['name', 'host', 'distancePc', 'semiMajorAu', 'massJup', 'radiusJup', 'temperatureK', 'starTeffK', 'starRadiusSun', 'kMag', 'discYear'];
export const IMAGED_PLANETS = ${JSON.stringify(rows)};
`;
  const config = (await prettier.resolveConfig(OUT)) ?? {};
  writeFileSync(
    OUT,
    await prettier.format(source, { ...config, parser: 'babel' })
  );
  console.log(`${rows.length} rows -> js/data/imagedPlanets.js`);
}
