#!/usr/bin/env node
// =============================================================================
// Which lesson steps run with a pinned integration step, as a table
// -----------------------------------------------------------------------------
//   node tools/lesson-step-pins.mjs           write docs/lesson-step-pins.md
//   node tools/lesson-step-pins.mjs --check   exit 1 if the file is stale
//
// One row per step whose scene the integrator moves: a scenario built from a
// setup, or a stage of an engine kind (js/lesson/stage.js, sceneIntegrated).
// The rule is the engine's own (js/lesson/stageGate.js, pinLessonStep): such a
// step is pinned to the bench's 1/60 s unless it holds the clock
// (js/timestep.js, holdsClock), in which case its scene does not run and
// there is nothing to pin. Steps on a quiet canvas, a portrait, a display
// stage or a prescribed binary have no row.
// =============================================================================

import { readFile, writeFile } from 'node:fs/promises';
import { INVESTIGATIONS } from '../js/data/investigations.js';
import { canvasAt } from '../js/lesson/canvasKind.js';
import { stageOf, sceneIntegrated, ENGINE_STAGES } from '../js/lesson/stage.js';
import { DEFAULT_SETTINGS } from '../js/appState.js';
import { SCENARIO_PRESETS, scenarioId } from '../js/scenarios.js';
import { STEP_SECONDS, holdsClock } from '../js/timestep.js';

const OUT = new URL('../docs/lesson-step-pins.md', import.meta.url);

/** The setup a step's scene was built from, as js/investigations.js finds it. */
function setupInForceAt(inv, i) {
  if (canvasAt(inv, i)?.kind === 'quiet') return null;
  for (let j = i; j >= 0; j--)
    if (inv.steps[j]?.setup) return inv.steps[j].setup;
  return null;
}

/** The speed a setup runs at: its own setting, else its scenario's, else the default. */
export function setupSpeed(setup) {
  const preset = SCENARIO_PRESETS[scenarioId(setup.scenario)] || {};
  return (
    setup.settings?.sim_speed ?? preset.sim_speed ?? DEFAULT_SETTINGS.sim_speed
  );
}

/**
 * Every step whose scene the integrator moves.
 * @returns {Array<object>} Rows: lesson, index, sid, type, scene, holds, pinned
 */
export function pinRows() {
  const rows = [];
  for (const inv of INVESTIGATIONS) {
    inv.steps.forEach((step, i) => {
      const canvas = canvasAt(inv, i)?.kind ?? null;
      const stage = stageOf(inv.steps, step);
      const setup = stage ? null : setupInForceAt(inv, i);
      if (!sceneIntegrated(canvas, stage, setup)) return;
      const holds = holdsClock(step);
      rows.push({
        lesson: inv.id,
        index: i + 1,
        sid: step.sid,
        type: step.type || 'read',
        scene: stage
          ? `stage: ${ENGINE_STAGES.find(k => stage[k])}`
          : setup.scenario,
        own: Boolean(step.setup || step.stage),
        holds,
        pinned: holds ? 0 : STEP_SECONDS,
      });
    });
  }
  return rows;
}

/** The table, as the file holds it. */
export function render(rows = pinRows()) {
  const pinned = rows.filter(r => r.pinned).length;
  const lessons = new Set(rows.map(r => r.lesson)).size;
  const head = [
    '# Lesson steps and the pinned integration step',
    '',
    'GENERATED by `node tools/lesson-step-pins.mjs`; do not edit. The rule is',
    "the engine's (`pinLessonStep` in `js/lesson/stageGate.js`): a step whose",
    'scene the integrator moves (a scenario setup, or a stage of kind',
    `${ENGINE_STAGES.map(k => `\`${k}\``).join(', ')}) runs with every frame`,
    "standing for the bench's 1/60 s, so a reading taken from it is the same",
    'on a 60 Hz screen, a 144 Hz screen and a throttled tab. A reading step',
    'that holds the clock (`holdsClock` in `js/timestep.js`) does not run and',
    'is not pinned. Closing the lesson lifts the pin.',
    '',
    `${rows.length} steps in ${lessons} lessons run on an integrated scene; ` +
      `${pinned} are pinned and ${rows.length - pinned} hold the clock.`,
    '',
    '| Lesson | Step | Id | Type | Scene | Own scene | Pinned step |',
    '|---|---|---|---|---|---|---|',
  ];
  const body = rows.map(
    r =>
      `| ${r.lesson} | ${r.index} | ${r.sid} | ${r.type} | ${r.scene} | ` +
      `${r.own ? 'yes' : 'inherited'} | ${r.pinned ? '1/60 s' : 'none (holds the clock)'} |`
  );
  return [...head, ...body, ''].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = render();
  if (process.argv.includes('--check')) {
    const have = await readFile(OUT, 'utf8').catch(() => '');
    if (have !== text) {
      console.error(
        'docs/lesson-step-pins.md is stale: run node tools/lesson-step-pins.mjs'
      );
      process.exit(1);
    }
    console.log('docs/lesson-step-pins.md is current');
  } else {
    await writeFile(OUT, text);
    console.log(
      `wrote docs/lesson-step-pins.md (${text.split('\n').length} lines)`
    );
  }
}
