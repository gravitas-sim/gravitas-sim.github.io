// =============================================================================
// tools/README.md, from the tools' own headers
// -----------------------------------------------------------------------------
//   node tools/build-tools-index.mjs           write tools/README.md
//   node tools/build-tools-index.mjs --check   fail if it is stale
//
// Every script in tools/ opens with a banner (or a JSDoc block) whose first
// line says what it is for. The index is those lines, and which npm scripts run each tool, so it
// cannot describe a tool that has gone or miss one that has arrived.
// =============================================================================

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(REPO, 'tools', 'README.md');

/** The first line of a script's banner, or null. */
export function purpose(src) {
  const lines = src.split('\n').filter(l => !l.startsWith('#!'));
  const i = lines.findIndex(l => /^\/\/ ={10,}/.test(l));
  // Or a JSDoc block at the top of the file: its first line.
  if (i < 0 && /^\/\*\*/.test(lines[0] || ''))
    return (lines[1] || '').replace(/^\s*\*\s?/, '').trim() || null;
  if (i < 0) return null;
  const line = (lines[i + 1] || '').replace(/^\/\/\s?/, '').trim();
  return line && !/^[-=]+$/.test(line) ? line : null;
}

export function renderIndex(root = REPO) {
  const scripts = JSON.parse(
    readFileSync(path.join(root, 'package.json'), 'utf8')
  ).scripts;
  const files = readdirSync(path.join(root, 'tools'))
    .filter(f => /\.(mjs|js)$/.test(f))
    .sort();
  const rows = files.map(f => {
    const what =
      purpose(readFileSync(path.join(root, 'tools', f), 'utf8')) ||
      '(no header)';
    const by = Object.entries(scripts)
      .filter(([, cmd]) => cmd.includes(`tools/${f}`))
      .map(([name]) => `\`npm run ${name}\``);
    return `| \`${f}\` | ${what.replace(/\|/g, '\\|')} | ${by.join(', ')} |`;
  });
  return [
    '# tools/',
    '',
    'Generated by `node tools/build-tools-index.mjs` from the first line of each',
    "tool's header. Do not edit; edit the header. `npm run generate` keeps it",
    'current, and the orchestrator checks it.',
    '',
    '| Tool | What it is for | Run by |',
    '| --- | --- | --- |',
    ...rows,
    '',
  ].join('\n');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = renderIndex();
  if (process.argv.includes('--check')) {
    let now = '';
    try {
      now = readFileSync(OUT, 'utf8');
    } catch {
      /* missing is stale */
    }
    if (now !== next) {
      console.error(
        'tools/README.md is stale. Run node tools/build-tools-index.mjs'
      );
      process.exit(1);
    }
    console.log('tools/README.md is current.');
  } else {
    writeFileSync(OUT, next);
    console.log('Wrote tools/README.md.');
  }
}
