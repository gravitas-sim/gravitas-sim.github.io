// Writes tests/fixtures/pulsars/oracle-inputs.json: the parameters and seeds of the series the
// independent oracle (tools/pulsar-oracle/oracle.py) regenerates for legs B1 to B5. No kernel output
// is written: the oracle builds the series itself (PULSARS.md). Run: node tools/pulsar-oracle/make-inputs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import process from 'node:process';
import { URL } from 'node:url';
import { stream } from '../../js/random/streams.js';

const THR = JSON.parse(
  readFileSync(
    new URL('../../tests/fixtures/pulsars/thresholds.json', import.meta.url),
    'utf8'
  )
);
const seed = THR.seeds.oracleInputs;
const draw = stream('forward', seed, 'b45');
const worlds = Array.from({ length: 24 }, (_, i) => ({
  period: 0.2 + 0.1 * draw(),
  dm: 20 + 100 * draw(),
  phase0: draw(),
  amplitude: 1,
  subchannels: 4,
  seed: `b45-${i}`,
}));
const out = {
  format: 'gravitas.pulsar-oracle-inputs/1',
  note: 'read as data by tools/pulsar-oracle/oracle.py; the series are regenerated by the oracle from these parameters (its own forward model and a port of the named random stream) and by the kernel generator, and compared by the validator',
  b1: {
    frequenciesMHz: [400, 600, 800, 1000, 1200, 1400, 1450, 1500],
    dms: [10, 60, 250],
  },
  b3: {
    world: {
      period: 0.2373,
      dm: 60,
      phase0: 0.3,
      amplitude: 1,
      subchannels: 4,
      seed: 'b3',
    },
    dm: 55.5,
    period: 0.2373,
    nbin: 64,
  },
  b2: {
    block: 3,
    periods: Array.from({ length: 40 }, (_, i) => 0.2 + (0.08 * i) / 39),
  },
  b45: {
    ranges: { dm: [10, 140], period: [0.15, 0.35] },
    worlds,
  },
};
writeFileSync(
  new URL('../../tests/fixtures/pulsars/oracle-inputs.json', import.meta.url),
  JSON.stringify(out) + '\n'
);
process.stdout.write(`wrote oracle-inputs.json, ${worlds.length} worlds\n`);
