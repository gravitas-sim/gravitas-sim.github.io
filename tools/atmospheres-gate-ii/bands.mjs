/* global console, process */
// Reduces the synthetic absorber's line-by-line cross-sections to a 16-point k-distribution per band (the pinned-table
// derivation rule of ATMOSPHERES_GATE_II.md: 8 Gauss-Legendre points on the lower 90 percent of the sorted band, 8 on the
// upper 10 percent) and writes js/kernels/atmospheres/bands.js. usage: node bands.mjs absorber.json
import { readFileSync, writeFileSync } from 'node:fs';
import { gauss } from '../../js/kernels/atmospheres/quadrature.js';
const abs = JSON.parse(readFileSync(process.argv[2], 'utf8'));
const MICRON = { strong: [1.3, 1.4], weak: [1.4, 1.5], window: [1.55, 1.65] };
const sig4 = x => Number(x.toPrecision(4));
const { x, w } = gauss(8);
const nodes = [];
for (let i = 0; i < 8; i++) nodes.push([0.45 * (1 + x[i]), 0.45 * w[i]]);
for (let i = 0; i < 8; i++) nodes.push([0.9 + 0.05 * (1 + x[i]), 0.05 * w[i]]);
const out = {};
for (const [name, s] of Object.entries(abs)) {
  const sorted = [...s].sort((a, b) => a - b);
  const N = sorted.length;
  const at = g => {
    // sorted[j] sits at cumulative (j + 0.5) / N; linear interpolation in log sigma
    const p = Math.min(Math.max(g * N - 0.5, 0), N - 1);
    const j = Math.min(Math.floor(p), N - 2);
    const f = p - j;
    return Math.exp((1 - f) * Math.log(sorted[j]) + f * Math.log(sorted[j + 1]));
  };
  const constant = sorted[N - 1] / sorted[0] < 1 + 1e-9;
  out[name] = {
    micron: MICRON[name],
    sigma: constant ? [sig4(sorted[0])] : nodes.map(([g]) => sig4(at(g))),
    weight: constant ? [1] : nodes.map(([, wt]) => wt),
  };
}
const body = Object.entries(out)
  .map(([k, v]) => `  ${k}: {\n    micron: ${JSON.stringify(v.micron)},\n    sigma: ${JSON.stringify(v.sigma)},\n    weight: ${JSON.stringify(v.weight)},\n  },`)
  .join('\n');
writeFileSync(
  'js/kernels/atmospheres/bands.js',
  `// The synthetic absorber's three bands as 16-point k-distributions (Prompt 201 spike; generated by tools/atmospheres-gate-ii/bands.mjs).\n// A synthetic absorber names no molecule: the production table is a pinned, cited cross-section table reduced the same way.\nexport const SYNTHETIC_BANDS = {\n${body}\n};\n`
);
console.log(Object.fromEntries(Object.entries(out).map(([k, v]) => [k, [v.sigma[0], v.sigma[15]]])));
