#!/usr/bin/env node
// =============================================================================
// The scoped accessibility conformance report (Roadmap III, Prompt 127)
// -----------------------------------------------------------------------------
//   node tools/conformance.mjs --write    write ACCESSIBILITY_CONFORMANCE.md
//   node tools/conformance.mjs --check    fail if it is stale
//
// The report is generated from tools/conformance/product.json (the product, its
// scope, its methods, the stated gaps) and tools/conformance/criteria.json (one
// record per WCAG 2.1 and 2.2 A and AA criterion). The status and the remarks
// are human judgments kept as data; this file only lays them out. The rules it
// enforces on that data live in tests/conformance.test.js: a criterion is
// "Supports" only when a method that can judge its whole scope covered it, and
// an axe pass alone is at most "Partially supports".
// =============================================================================

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const OUT = path.join(REPO, 'ACCESSIBILITY_CONFORMANCE.md');
const read = f => JSON.parse(readFileSync(path.join(REPO, f), 'utf8'));

export const load = () => ({
  product: read('tools/conformance/product.json'),
  criteria: read('tools/conformance/criteria.json'),
  version: read('package.json').version,
});

const cell = s => String(s).replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function render({ product, criteria, version }) {
  const out = [];
  const w = (...l) => out.push(...l);
  const counts = {};
  for (const c of criteria) counts[c.status] = (counts[c.status] || 0) + 1;
  const methods = new Map(product.methods.map(m => [m.id, m]));

  w(
    '# Accessibility conformance report',
    '',
    '<!-- Generated by `node tools/conformance.mjs --write` from tools/conformance/*.json. Do not edit by hand. -->',
    '',
    `**Product:** ${product.product} ${version}  `,
    `**Standard:** ${product.standard}  `,
    `**Date of evaluation:** ${product.date}`,
    '',
    '## What this report is',
    '',
    `This is ${product.evaluation} It does not claim conformance. A criterion is reported **Supports** only when a method that can judge its whole scope covered the whole scope; a pass by axe-core alone is at most **Partially supports**, with the rules named. **Not evaluated** is used where no method here looked, which is neither a claim of support nor of failure. [ACCESSIBILITY.md](ACCESSIBILITY.md) says what was fixed and what cannot be; its list of honest limitations and this report must agree, and a test fails when they do not.`,
    '',
    '## Scope: the workflows evaluated',
    '',
    'Ten student workflows and the instructor path, by the end-to-end specs that exercise them. Each is judged by the methods below on the surfaces and states those specs open.',
    '',
    '| Workflow | What the student does | Specs |',
    '|---|---|---|'
  );
  for (const s of product.scope.student)
    w(
      `| ${s.id} | ${cell(s.name)} | ${s.specs.map(x => `\`${x}\``).join(', ')} |`
    );
  const i = product.scope.instructor;
  w(
    `| ${i.id} | ${cell(i.name)} | ${i.specs.map(x => `\`${x}\``).join(', ')} |`,
    '',
    `Outside the scope: ${product.scope.outside}`,
    '',
    '## Methods',
    '',
    '| Method | What it is, and what it cannot judge |',
    '|---|---|'
  );
  for (const m of product.methods)
    w(`| **${cell(m.name)}** (\`${m.id}\`) | ${cell(m.detail)} |`);
  w(
    '',
    'No method here is a test with assistive-technology users. **Assistive-technology user validation has not occurred**, so no criterion that depends on how a screen reader, switch or voice control behaves is reported as supported.',
    '',
    '## Summary',
    '',
    '| Status | Criteria |',
    '|---|---|'
  );
  for (const s of [
    'Supports',
    'Partially supports',
    'Does not support',
    'Not applicable',
    'Not evaluated',
  ])
    w(`| ${s} | ${counts[s] || 0} |`);
  w(
    '',
    `${criteria.length} criteria in all: every Level A and AA criterion of WCAG 2.1 and 2.2 (4.1.1 is listed because 2.1 has it; 2.2 removed it).`
  );

  for (const level of ['A', 'AA']) {
    w(
      '',
      `## Level ${level}`,
      '',
      '| Criterion | Status | Evaluated by | Remarks |',
      '|---|---|---|---|'
    );
    for (const c of criteria.filter(x => x.level === level)) {
      const by = c.methods.length
        ? c.methods.map(m => methods.get(m).name).join('; ') +
          (c.axeRules.length
            ? `. axe rules: ${c.axeRules.map(r => `\`${r}\``).join(', ')}`
            : '')
        : 'none';
      w(
        `| **${c.id}** ${cell(c.name)} (WCAG ${c.since}) | ${c.status} | ${cell(by)} | ${cell(c.remarks)} |`
      );
    }
  }

  const rules = new Map();
  for (const c of criteria)
    for (const r of c.axeRules)
      (rules.get(r) || rules.set(r, []).get(r)).push(c.id);
  w(
    '',
    '## Which axe rules were counted toward which criteria',
    '',
    'A rule tests a part of a criterion, never the whole of it. This is the mapping used above; the rest of each criterion is covered by the other methods or not at all.',
    '',
    '| axe rule | Criteria it counts toward |',
    '|---|---|'
  );
  for (const [r, ids] of [...rules].sort((a, b) => a[0].localeCompare(b[0])))
    w(`| \`${r}\` | ${ids.join(', ')} |`);

  w(
    '',
    '## Stated gaps',
    '',
    'From [ACCESSIBILITY.md](ACCESSIBILITY.md), "Honest limitations". Each is a limit no amount of ARIA removes; the criteria it touches are never reported as Supports.',
    '',
    '| Limitation | Criteria |',
    '|---|---|'
  );
  for (const g of product.gaps)
    w(`| ${cell(g.heading)} | ${g.criteria.join(', ')} |`);

  w(
    '',
    '## The generated documents',
    '',
    `- **Instructor documents (PDF).** ${product.documents.instructorPdfs}`,
    `- **Student reports.** ${product.documents.studentReports}`,
    `- Affects criteria: ${product.documents.criteria.join(', ')}. For the untagged instructor PDFs those criteria are **Does not support**; the web pages that carry the same content are the route for a reader who needs structure.`,
    '',
    '## Updating this report',
    '',
    'Edit tools/conformance/criteria.json (a status and its remarks) or product.json, then run `node tools/conformance.mjs --write`. A change to a status that makes a criterion Supports must name the method that judged its whole scope.',
    ''
  );
  return out.join('\n');
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const text = render(load());
  if (process.argv.includes('--write')) {
    writeFileSync(OUT, text);
    console.log('wrote ACCESSIBILITY_CONFORMANCE.md');
  } else if (readFileSync(OUT, 'utf8') !== text) {
    console.error(
      'ACCESSIBILITY_CONFORMANCE.md is stale: run node tools/conformance.mjs --write'
    );
    process.exit(1);
  }
}
