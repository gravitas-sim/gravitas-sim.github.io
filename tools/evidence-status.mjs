#!/usr/bin/env node
// =============================================================================
// The evidence-status record (Roadmap III, Prompt 122, rule 7.5.10)
// -----------------------------------------------------------------------------
// tools/evidence-status.json holds, per public claim, the scope, version,
// evidence class (S software works, V-internal and V-external science valid,
// A adopted, L learning measured), method, evaluator, artifact, limitations and
// date. This writes docs/evidence-status.md from it: the four-column statement
// and the evidence section of a release's notes. The release notes and the
// statement are generated, never typed.
//
//   node tools/evidence-status.mjs --write    write docs/evidence-status.md
//   node tools/evidence-status.mjs --check    fail if it is stale
// =============================================================================

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const RECORD = path.join(REPO, 'tools', 'evidence-status.json');
export const OUT = path.join(REPO, 'docs', 'evidence-status.md');

const COLUMNS = [
  ['S', 'Software works', ['S']],
  ['V', 'Science valid', ['V-internal', 'V-external']],
  ['A', 'Adopted', ['A']],
  ['L', 'Learning measured', ['L']],
];

export function loadRecord() {
  return JSON.parse(readFileSync(RECORD, 'utf8'));
}

const mark = c =>
  c.status === 'UNKNOWN' ? 'UNKNOWN (not established)' : c.status;

export function render(record) {
  const out = [];
  out.push('# Evidence status');
  out.push('');
  out.push(
    'Generated by `node tools/evidence-status.mjs --write` from `tools/evidence-status.json`. Do not edit by hand. Four facts are never substituted for one another: software works (S), science valid (V), adopted (A), learning measured (L). UNKNOWN means no evidence exists in this repository; it is not a failure and it supports no claim.'
  );
  out.push('');
  out.push('## The four-column statement');
  out.push('');
  out.push('| ' + COLUMNS.map(c => c[1]).join(' | ') + ' |');
  out.push('| ' + COLUMNS.map(() => '---').join(' | ') + ' |');
  const cells = COLUMNS.map(([, , classes]) => {
    const items = record.claims.filter(c => classes.includes(c.class));
    return items.map(c => `${mark(c)}: ${c.claim}`).join('<br>');
  });
  out.push('| ' + cells.join(' | ') + ' |');
  out.push('');
  out.push('## Evidence section for release notes');
  out.push('');
  for (const [, label, classes] of COLUMNS) {
    out.push(`**${label}.**`);
    for (const c of record.claims.filter(x => classes.includes(x.class)))
      out.push(
        `- ${mark(c)} (${c.class}, ${c.version}): ${c.claim} ${c.limitations}`
      );
    out.push('');
  }
  out.push('## Records');
  out.push('');
  out.push('| Id | Class | Status | Scope | Method | Evaluator | Artifact | Date |');
  out.push('| --- | --- | --- | --- | --- | --- | --- | --- |');
  for (const c of record.claims)
    out.push(
      `| ${c.id} | ${c.class} | ${c.status} | ${c.scope} | ${c.method} | ${c.evaluator} | ${c.artifact ? '`' + c.artifact + '`' : ''} | ${c.date} |`
    );
  out.push('');
  return out.join('\n');
}

function main() {
  const text = render(loadRecord());
  if (process.argv.includes('--write')) {
    writeFileSync(OUT, text);
    console.log(`wrote ${path.relative(REPO, OUT)}`);
    return;
  }
  const current = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
  if (current !== text) {
    console.error(
      'docs/evidence-status.md is stale: run node tools/evidence-status.mjs --write'
    );
    process.exit(1);
  }
  console.log('docs/evidence-status.md is current');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
