#!/usr/bin/env node
// =============================================================================
// The lesson's three engine-made systems (Prompt 226, TTV.md)
// -----------------------------------------------------------------------------
//   node tools/ttv-pack.mjs            write js/data/ttvPack.js
//   node tools/ttv-pack.mjs --check    fail if the file is not what the engine makes
//
// The three systems of tests/fixtures/ttv/thresholds.json (S1 near 2:1, S2 near 3:2, S3 far
// from resonance) are integrated by the engine (js/physics.js, headless, the forward model of
// js/kernels/ttv), each transit gets a seeded noisy window of light curve, and the kernel's
// template fit measures it. What ships is the engine's own transit time, the measured time and
// its one-sigma, per transit. SYNTHETIC, with its truth manifest: no star was observed.
// =============================================================================

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import prettier from 'prettier';
import { installDomShim } from '../js/validation/domShim.js';
import { makeLab } from '../js/validation/harness.js';
import {
  engineTransitTimes,
  linearEphemeris,
  measureTransitTime,
  transitWindow,
} from '../js/kernels/ttv/index.js';

const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const THR = JSON.parse(
  readFileSync(path.join(ROOT, 'tests/fixtures/ttv/thresholds.json'), 'utf8')
);
const OUT = path.join(ROOT, 'js/data/ttvPack.js');
const AM1_PPM = THR.amendments.find(a => a.id === 'AM1').added.find(a => a.id === 'C1b').sigma_ppm;
// AM1: the curvature sigma is calibrated when the timing precision is a fraction of the cadence, so the pinned set uses the amended noise.
const LC = { ...THR.lightCurve, sigma_ppm: AM1_PPM };
const SEED = 'ttv-pack-226';
const d5 = x => Number(x.toFixed(5));
const d6 = x => Number(x.toPrecision(4));

installDomShim();
const physics = await import('../js/physics.js');
const lab = makeLab(physics);
const systems = {};
for (const id of ['S1', 'S2', 'S3']) {
  const s = THR.systems[id];
  const { times } = engineTransitTimes({
    physics,
    lab,
    system: s,
    baseline: s.baseline_d,
  });
  const planets = [0, 1].map(k => {
    const P = k ? s.P2 : s.P1;
    const eph = linearEphemeris(
      times[k].map((_, i) => i),
      times[k]
    );
    const n = [];
    const truth = [];
    const time = [];
    const sigma = [];
    times[k].forEach((tt, i) => {
      const tpl = { P, k: LC.k, aRs: LC.aRs, b: LC.b, q1: LC.q1, q2: LC.q2 };
      const w = transitWindow({
        trueTime: tt,
        center: eph.T0 + i * eph.P,
        template: tpl,
        sigma: LC.sigma_ppm * 1e-6,
        cadence: LC.cadence_d,
        halfWidth: LC.window_halfwidth_d,
        seed: SEED,
        labels: [id, k, i],
      });
      const m = measureTransitTime({
        t: w.t,
        flux: w.flux,
        sigma: w.sigma,
        template: tpl,
        guess: eph.T0 + i * eph.P,
      });
      if (m.status !== 'ok') return;
      n.push(i);
      truth.push(d5(tt));
      time.push(d5(m.time));
      sigma.push(d6(m.sigma));
    });
    return { P, mu: k ? s.mu2 : s.mu1, n, truth, time, sigma };
  });
  systems[id] = { what: s.what, j: s.j, baseline: s.baseline_d, planets };
}
const body = `// =============================================================================
// The lesson's three engine-made systems: GENERATED by tools/ttv-pack.mjs, do not edit.
// SYNTHETIC. Each system is two planets on a star, integrated by the engine (js/physics.js,
// Velocity Verlet, 2000 steps per inner period) with the committed values of
// tests/fixtures/ttv/thresholds.json; every transit has a noisy window of light curve
// (${LC.sigma_ppm} ppm per ${(LC.cadence_d * 1440).toFixed(0)}-minute point, seed ${SEED}) measured by the kernel's template
// fit. truth: the engine's transit time; time and sigma: the measurement. Days; mu is the
// planet-to-star mass ratio. No star was observed.
// =============================================================================

export const TTV_PACK = ${JSON.stringify({ seed: SEED, lightCurve: { ...LC }, systems })};
`;
const formatted = await prettier.format(body, {
  ...(await prettier.resolveConfig(OUT)),
  filepath: OUT,
});
if (process.argv.includes('--check')) {
  const have = readFileSync(OUT, 'utf8');
  if (have !== formatted) {
    console.error(
      'js/data/ttvPack.js is not what the engine makes; run node tools/ttv-pack.mjs'
    );
    process.exitCode = 1;
  } else console.log('ttvPack.js matches the engine');
} else {
  writeFileSync(OUT, formatted);
  console.log('wrote', OUT, formatted.length, 'bytes');
}
