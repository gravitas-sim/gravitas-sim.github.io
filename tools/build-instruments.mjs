#!/usr/bin/env node
// =============================================================================
// npm run instruments:data  /  npm run instruments:check
// -----------------------------------------------------------------------------
// Writes js/data/instruments.js from the committed source table,
// tools/instruments/*.json (INSTRUMENTS.md): sources.json (every citation, with
// its retrieval date and rights basis), sites.json, and one file per facility.
// The source table is the thing a person edits and reviews; the module is what
// the code reads, and it is never edited by hand.
//
// It refuses to write a table the validator (js/instruments/validate.js) finds
// a fault in: a value without a source or a registry unit, a source nothing
// cites, a site nothing uses. `--check` rewrites nothing and fails when the
// committed module is not exactly what the source would produce (the module is
// a Prettier fixed point, so it is the same under `npm run format`).
// =============================================================================

import { readdir, readFile, writeFile } from 'node:fs/promises';
import * as prettierNamespace from 'prettier';
import {
  CLASSES,
  describeProblems,
  validateLibrary,
} from '../js/instruments/validate.js';

// Prettier's exports arrive in two shapes (Jest's ESM interop and Node's own
// loader); same reason as tools/build-irreversibility-audit.mjs.
const prettier = prettierNamespace.format
  ? prettierNamespace
  : prettierNamespace.default;

const DIR = 'tools/instruments';
const OUT = 'js/data/instruments.js';
const check = process.argv.includes('--check');
const NOT_FACILITY = new Set(['sources.json', 'sites.json']);

/** Read the source table: { sources, sites, facilities } in a fixed order. */
export async function readSourceTable(dir = DIR) {
  const json = async name =>
    JSON.parse(await readFile(`${dir}/${name}`, 'utf8'));
  const sources = (await json('sources.json')).sources;
  const sites = (await json('sites.json')).sites;
  const names = (await readdir(dir))
    .filter(n => n.endsWith('.json') && !NOT_FACILITY.has(n))
    .sort();
  const facilities = [];
  for (const n of names) facilities.push(await json(n));
  // Real facilities by class, then the typical entries; id breaks ties.
  const rank = f => (f.typical ? CLASSES.length : CLASSES.indexOf(f.class));
  facilities.sort((a, b) => rank(a) - rank(b) || a.id.localeCompare(b.id));
  return { sources, sites, facilities };
}

/** The text of the generated module. */
export async function render(table) {
  const header = `// Generated by tools/build-instruments.mjs from tools/instruments/*.json.
// Do not edit by hand: edit the source table and run \`npm run instruments:data\`.
// The instrument library: a few facilities with every value cited, and typical
// entries labelled as such. A value the sources do not state is absent.
// Schema, sources and rules: INSTRUMENTS.md. Validator: js/instruments/validate.js.
`;
  const body = `
export const SOURCES = ${JSON.stringify(table.sources)};

export const SITES = ${JSON.stringify(table.sites)};

export const FACILITIES = ${JSON.stringify(table.facilities)};
`;
  const options = JSON.parse(await readFile('.prettierrc.json', 'utf8'));
  return prettier.format(header + body, { ...options, parser: 'babel' });
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const table = await readSourceTable();
  const problems = validateLibrary(table);
  if (problems.length) {
    console.error(
      `${problems.length} problem(s) in ${DIR}:\n${describeProblems(problems)}`
    );
    process.exit(1);
  }
  const text = await render(table);
  if (check) {
    const current = await readFile(OUT, 'utf8').catch(() => '');
    if (current !== text) {
      console.error(`${OUT} is stale: run npm run instruments:data`);
      process.exit(1);
    }
    console.log(`${OUT} is current (${table.facilities.length} facilities).`);
  } else {
    await writeFile(OUT, text);
    console.log(
      `wrote ${OUT}: ${table.facilities.length} facilities, ${Object.keys(table.sources).length} sources.`
    );
  }
}
